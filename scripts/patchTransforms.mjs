// scripts/patchTransforms.mjs
// Pure string-level transforms used by the asar patch pipeline (Task 6) to inject
// the Qoder Usage Monitor into a client index.html: CSP connect-src allowance +
// loader <script> tag, both marker-annotated so they can be re-patched (port swap)
// or fully removed (uninstall) byte-exactly.

const CSP_MARKER = '<!-- qum:csp -->';
// Separate marker for the merged shape (URL appended to a pre-existing
// connect-src). Without it a degenerate merge of `connect-src 'self';` would be
// byte-identical to a fresh injection and unpatch could not tell which removal
// is safe, breaking byte-exact unpatch.
const CSP_MERGED_MARKER = '<!-- qum:csp-merged -->';
const LOADER_SNIPPET =
  '\n<script type="module" crossorigin src="./monitor/loader.js"></script>\n<!-- qum:loader -->';

const CSP_META_RE = /<meta[^>]*http-equiv="Content-Security-Policy"[^>]*>/i;
// Exact shape injected by injectCsp (case: no pre-existing connect-src).
const INJECTED_DIRECTIVE_RE = / connect-src 'self' http:\/\/127\.0\.0\.1:\d+;/;
// ` http://127.0.0.1:<port>` appended at the end of an existing connect-src value.
const APPENDED_URL_RE = /(connect-src[^;"]*?) http:\/\/127\.0\.0\.1:\d+(?=[;"])/i;

export function isPatched(html) {
  return /<!-- qum:(?:csp(?:-merged)?|loader) -->/.test(html);
}

// Remove every qum-injected bit. CSP removal is gated on the qum markers so a
// client's own connect-src entry for 127.0.0.1 is never touched, and the marker
// selects the removal shape: a merged directive only loses the appended origin
// (the client's own content is restored), a freshly injected directive is removed
// whole.
function stripQum(html) {
  let out = html.split(LOADER_SNIPPET).join('');
  if (out.includes(CSP_MERGED_MARKER)) {
    out = out.split(CSP_MERGED_MARKER).join('');
    out = out.replace(APPENDED_URL_RE, '$1'); // restore the pre-existing directive
  } else if (out.includes(CSP_MARKER)) {
    out = out.split(CSP_MARKER).join('');
    out = out.replace(INJECTED_DIRECTIVE_RE, ''); // remove the whole injected directive
  }
  return out;
}

function injectCsp(html, port) {
  const url = `http://127.0.0.1:${port}`;
  return html.replace(CSP_META_RE, (meta) => {
    let patched, marker;
    if (/connect-src/i.test(meta)) {
      // Append our origin at the end of the existing directive value
      // ([^;"]* cannot cross the directive's ';' or the attribute's closing '"').
      patched = meta.replace(/(connect-src[^;"]*)/i, (d) => d.replace(/\s+$/, '') + ` ${url}`);
      marker = CSP_MERGED_MARKER;
    } else if (meta.includes(`default-src 'self';`)) {
      patched = meta.replace(`default-src 'self';`, `default-src 'self'; connect-src 'self' ${url};`);
      marker = CSP_MARKER;
    } else {
      return meta; // unknown CSP shape: never guess, never mark
    }
    return patched + marker;
  });
}

function injectLoader(html) {
  const i = html.indexOf('</head>');
  return i === -1 ? html : html.slice(0, i) + LOADER_SNIPPET + html.slice(i);
}

export function patchIndexHtml(html, { port } = {}) {
  if (!Number.isInteger(port) || port <= 0 || port > 65535) {
    throw new TypeError(`patchIndexHtml: invalid port ${port}`);
  }
  // Strip-then-inject makes patching idempotent and port swaps stale-free.
  return injectLoader(injectCsp(stripQum(html), port));
}

export function unpatchIndexHtml(html) {
  return stripQum(html);
}

// Placeholder until Task 8 supplies the real loader body via `implBody`.
const LOADER_IMPL_STUB = `  // qum loader stub — probing loop + widget bootstrap land in Task 8.`;

// Renders loader.js source with inlined constants (spec §7.4). The implementation
// body goes only into the /*__QUM_LOADER_IMPL__*/ region; Task 8 passes the real
// body as opts.implBody, defaulting to the side-effect-free stub above.
export function renderLoader({ bootstrapCode, port, version, implBody = LOADER_IMPL_STUB }) {
  return `(function () {
'use strict';
/* Qoder Usage Monitor loader v${version} — generated by the installer, do not edit in place. */
const QUM_BOOTSTRAP = ${JSON.stringify(String(bootstrapCode))};
const QUM_PORT = ${Number(port)};
const QUM_VERSION = ${JSON.stringify(String(version))};
  /*__QUM_LOADER_IMPL__*/
${implBody}
})();
`;
}
